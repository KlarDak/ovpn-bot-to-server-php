CREATE TEMPORARY TABLE connector_probe (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    label VARCHAR(255) NOT NULL UNIQUE,
    optional_value VARCHAR(255) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TEMPORARY TABLE users (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    telegram_id BIGINT NULL UNIQUE,
    email TEXT NULL,
    username TEXT NULL,
    language VARCHAR(100) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activity_at DATETIME NULL,
    expired_at DATETIME NULL,
    last_payment_at DATETIME NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    disabled_at DATETIME NULL,
    is_dropped TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TEMPORARY TABLE accesses (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    user_id INT NOT NULL,
    uuid CHAR(36) NOT NULL UNIQUE,
    name TEXT NULL,
    type VARCHAR(32) NOT NULL,
    server_id INT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    disabled_at DATETIME NULL,
    is_dropped TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TEMPORARY TABLE servers (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    host VARCHAR(255) NOT NULL,
    port INT UNSIGNED NOT NULL,
    api_endpoint TEXT NOT NULL,
    encrypt_secret_code TEXT NOT NULL,
    type VARCHAR(32) NOT NULL,
    subs_url TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(32) NOT NULL,
    disabled_at DATETIME NULL,
    is_dropped TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TEMPORARY TABLE subs (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    short_code VARCHAR(100) NOT NULL UNIQUE,
    server_id INT UNSIGNED NOT NULL,
    access_id INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_used TINYINT(1) NOT NULL DEFAULT 0,
    used_at DATETIME NULL,
    is_dropped TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
